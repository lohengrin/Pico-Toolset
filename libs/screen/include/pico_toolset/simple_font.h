// Fetch the glyph for an ASCII char (zero-width glyph for undefined/out-of-
// range chars).
inline const BitmapGlyph& glyph_at(const GlyphFont& font, char c) {
    uint8_t idx = static_cast<uint8_t>(c) - 0x20;
    if (c < 0x20 || idx >= 96) {
        static const BitmapGlyph kBlank{0, 0, nullptr};
        return kBlank;
    }
    return font.glyphs[idx];
}

